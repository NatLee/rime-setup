為什麼要有這個檔：
  原本 '/ 是一張 47 列的平面清單，page_size 只有 6，要翻 8 頁才看得完，
  而且內容是 `[-.0-9]+[ + - * / ^ ( ) ]...` 這種正規表示式，看不出怎麼用。
  更糟的是每一列的候選「文字」是 ①②③ 這種圈圈數字，選下去只會在文件裡
  上屏一個圈圈數字 —— 看起來就像「按了沒反應」。

改成：
  '/        → 4 個大類，一頁看完
  '/dt '/ca → 子選單
  選中一列 → 依該列的 go/run 跳到對應代碼或直接執行，不再上屏垃圾字元。

每一列的欄位：
  label  顯示文字（候選的 comment；候選 text 一律留空，選中不上屏任何東西）
  go     選中後把輸入改寫成「前綴 .. go」，例如 go="f" → '/f
  run    選中後直接執行 p_run_pattern 裡該鍵的動作（開檔案/網址/腳本）
  go 與 run 都沒有的列＝純說明，選中只會收起選單。
--]]

