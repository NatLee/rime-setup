--[[
分層選單資料 —— translator（負責顯示）與 processor（負責跳轉/執行）共用同一份表。

為什麼要有這個檔：
  原本 '/ 是一張 47 列的平面清單，page_size 只有 6，要翻 8 頁才看得完，
  而且內容是 `[-.0-9]+[ + - * / ^ ( ) ]...` 這種正規表示式，看不出怎麼用。
  更糟的是每一列的候選「文字」是 ①②③ 這種圈圈數字，選下去只會在文件裡
  上屏一個圈圈數字 —— 看起來就像「按了沒反應」。

改成：
  '/        → 4 個大類，一頁看完
  '/dt '/num → 子選單
  選中一列 → 依該列的 go/run 跳到對應代碼或直接執行，不再上屏垃圾字元。

每一列的欄位：
  key    這一列對應的代碼（不含前綴）。同時是候選的「文字」，會顯示成 '/dt 這樣，
         順便讓你看得到代碼、下次可以直接打。
  label  說明文字（候選的 comment）
  run    有設的話，選中就直接執行 p_run_pattern 裡該鍵的動作（開檔案/網址/腳本）；
         沒設的話，選中就把輸入改寫成「前綴 .. key」，進到那個功能。

⚠ key 在同一份選單裡必須唯一，而且不能讓兩列的候選文字相同 ——
  engine/filters 末端掛著 uniquifier，**文字相同的候選會被合併掉**。
  舊版之所以把 ①②③ 塞進候選文字，就是為了讓每列不同；曾經試過把文字留空，
  結果六列被 uniquifier 併成一列，畫面上只剩第一列。
--]]

